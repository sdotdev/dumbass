import { execFile } from "node:child_process";
import { assertAuthorized } from "./consent.mjs";

// Optional hosted rendering through GitHub Actions. It is a route for platforms the user's own machine
// cannot render, never a default. Nothing here pushes code, edits repository settings, writes
// secrets or installs a workflow: the workflow is produced as text for the user to review and commit,
// and execution requires a matching, unexpired authorization record.

const SAFE = {
  id: /^[A-Za-z0-9._-]{1,64}$/,
  swiftFile: /^(?!\/)(?!.*\.\.)[A-Za-z0-9._/-]{1,200}\.swift$/,
  sha40: /^[a-f0-9]{40}$/,
  dir: /^(?!\/)(?!.*\.\.)[A-Za-z0-9._/-]{1,200}$/,
  gradleModule: /^[A-Za-z0-9_-]{1,64}$/,
  variant: /^[A-Z][A-Za-z0-9]{0,30}$/,
  java: /^(17|21|22|23|24|25)$/,
  xcode: /^[0-9]{1,2}(\.[0-9]{1,2}){0,2}$/,
  runner: /^(macos|ubuntu)-[0-9]{2}(\.[0-9]{2})?(-arm64)?$/,
  device: /^(iphone|iphone-se|iphone-pro-max|ipad)$/,
  theme: /^(light|dark)$/,
};

function check(kind, value, label) {
  if (typeof value !== "string" || !SAFE[kind].test(value)) throw new Error(`Invalid ${label}: ${JSON.stringify(value)}`);
  return value;
}

export const SWIFTUI_RENDER_REPOSITORY = "https://github.com/olliewagner/swiftui-render.git";

/**
 * Builds a workflow for review. Every interpolated value is validated first and none comes from the
 * network, so the text cannot be steered by repository content.
 * @param {{
 *   kind: "macos-swiftui-render" | "linux-gradle",
 *   retentionDays: number, artifactName: string,
 *   runnerImage?: string, xcodeVersion?: string,
 *   swiftuiRenderRevision?: string,
 *   screens?: { id: string, file: string, device?: string, theme?: string }[],
 *   gradle?: { tool: "paparazzi" | "mugshot", module: string, moduleDir: string, variant?: string, javaVersion: string },
 * }} spec
 */
export function buildWorkflow(spec) {
  if (!Number.isInteger(spec.retentionDays) || spec.retentionDays < 1 || spec.retentionDays > 30) throw new Error("Retention must be 1 to 30 days");
  const artifact = check("id", spec.artifactName, "artifact name");
  if (spec.kind === "macos-swiftui-render") return macosWorkflow(spec, artifact);
  if (spec.kind === "linux-gradle") return linuxWorkflow(spec, artifact);
  throw new Error(`Unknown workflow kind ${spec.kind}`);
}

const HEADER = (title) => `# ${title}
# Generated by Dumbass for review. It is not installed automatically: read it, then commit it yourself if you agree.
# It starts only by hand (workflow_dispatch), never from a pull request, receives no secrets from Dumbass,
# and asks for read-only access to repository contents.
`;

function macosWorkflow(spec, artifact) {
  const sha = check("sha40", spec.swiftuiRenderRevision, "swiftui-render revision (a full commit SHA you have reviewed; it is deliberately not defaulted)");
  const runner = check("runner", spec.runnerImage ?? "macos-15", "runner image");
  const screens = spec.screens ?? [];
  if (!screens.length) throw new Error("At least one screen is required");
  const seen = new Set();
  const renderCommands = screens.map((s) => {
    const id = check("id", s.id, "screen id");
    if (seen.has(id)) throw new Error(`Duplicate screen id ${id}`);
    seen.add(id);
    const file = check("swiftFile", s.file, "screen file");
    const device = check("device", s.device ?? "iphone", "device");
    const theme = s.theme ? check("theme", s.theme, "theme") : "light";
    return `swiftui-render render '${file}' --${device}${theme === "dark" ? " --dark" : ""} -o "$OUT/${id}.png" --json`;
  });
  const xcode = spec.xcodeVersion
    ? `      - name: Select Xcode
        run: |
          set -eu
          app="/Applications/Xcode_${check("xcode", spec.xcodeVersion, "Xcode version")}.app"
          test -d "$app"
          sudo xcode-select -s "$app"
`
    : "";
  const yaml = `${HEADER("Dumbass hosted macOS rendering for SwiftUI")}name: Dumbass mobile render (macOS)
on:
  workflow_dispatch:
    inputs:
      expected_sha:
        description: Full commit SHA this run must be executing
        required: true
        type: string
permissions:
  contents: read
jobs:
  render:
    runs-on: ${runner}
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v5
        with:
          persist-credentials: false
      - name: Verify revision
        env:
          EXPECTED_SHA: \${{ inputs.expected_sha }}
        run: |
          set -eu
          test "$(git rev-parse HEAD)" = "$EXPECTED_SHA"
${xcode}      - name: Build swiftui-render at a pinned revision
        run: |
          set -eu
          tool="$RUNNER_TEMP/swiftui-render-src"
          git clone --quiet ${SWIFTUI_RENDER_REPOSITORY} "$tool"
          git -C "$tool" checkout --quiet ${sha}
          (cd "$tool" && swift build -c release)
          echo "$tool/.build/release" >> "$GITHUB_PATH"
      - name: Render screens
        run: |
          set -eu
          OUT="$RUNNER_TEMP/dumbass-out"
          mkdir -p "$OUT"
${renderCommands.map((c) => `          ${c}`).join("\n")}
      - name: Upload screenshots
        uses: actions/upload-artifact@v4
        with:
          name: ${artifact}
          path: \${{ runner.temp }}/dumbass-out
          retention-days: ${spec.retentionDays}
          if-no-files-found: error
      - name: Clean up
        if: always()
        run: |
          rm -rf "$RUNNER_TEMP/dumbass-out" "$RUNNER_TEMP/swiftui-render-src"
`;
  return { yaml, runnerImage: runner, commands: renderCommands.map((c) => c.replace('"$OUT/', "OUT/").replace('"', "")), screens: screens.map((s) => s.id) };
}

function linuxWorkflow(spec, artifact) {
  const g = spec.gradle;
  if (!g) throw new Error("Gradle settings are required");
  if (g.tool !== "paparazzi" && g.tool !== "mugshot") throw new Error("Unknown gradle tool");
  const runner = check("runner", spec.runnerImage ?? "ubuntu-24.04", "runner image");
  const module = check("gradleModule", g.module, "gradle module");
  const moduleDir = check("dir", g.moduleDir, "module directory");
  const variant = check("variant", g.variant ?? "Debug", "variant");
  const java = check("java", g.javaVersion, "Java version");
  const taskName = g.tool === "paparazzi" ? `record Paparazzi${variant}` : `record Mugshot${variant}`;
  const task = `:${module}:${taskName.replace(" ", "")}`;
  const snapshots = `${moduleDir}/src/test/snapshots`;
  const yaml = `${HEADER("Dumbass hosted Linux rendering for Android")}name: Dumbass mobile render (Linux)
on:
  workflow_dispatch:
    inputs:
      expected_sha:
        description: Full commit SHA this run must be executing
        required: true
        type: string
permissions:
  contents: read
jobs:
  render:
    runs-on: ${runner}
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@v5
        with:
          persist-credentials: false
      - name: Verify revision
        env:
          EXPECTED_SHA: \${{ inputs.expected_sha }}
        run: |
          set -eu
          test "$(git rev-parse HEAD)" = "$EXPECTED_SHA"
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: '${java}'
      - name: Clear previously committed snapshots so only fresh output is returned
        run: |
          set -eu
          rm -rf '${snapshots}'
      - name: Render
        run: |
          set -eu
          chmod +x ./gradlew
          ./gradlew --no-daemon ${task}
      - name: Upload screenshots
        uses: actions/upload-artifact@v4
        with:
          name: ${artifact}
          path: ${snapshots}
          retention-days: ${spec.retentionDays}
          if-no-files-found: error
      - name: Clean up
        if: always()
        run: |
          rm -rf '${snapshots}'
`;
  return { yaml, runnerImage: runner, commands: [`./gradlew --no-daemon ${task}`], screens: [] };
}

export class HostedRunError extends Error {
  constructor(message, details = {}) {
    super(message);
    this.name = "HostedRunError";
    this.details = details;
  }
}

/**
 * @typedef {{
 *   workflowExists(args: { repository: string, workflow: string, revision: string }): Promise<boolean>,
 *   dispatch(args: { repository: string, workflow: string, ref: string, revision: string }): Promise<{ runId: string }>,
 *   waitForRun(args: { repository: string, runId: string }): Promise<{ conclusion: string }>,
 *   download(args: { repository: string, runId: string, artifactName: string, directory: string }): Promise<string[]>,
 *   deleteArtifact(args: { repository: string, runId: string, artifactName: string }): Promise<boolean>
 * }} HostedTransport
 */

/**
 * Runs an authorized hosted render. Authorization is checked first, before any transport call, so a
 * missing or mismatched record can never start remote work.
 * @param {{ authorization: unknown, plan: import("./consent.mjs").RemotePlan & { ref: string, artifactName: string }, transport: HostedTransport, directory: string, now?: Date }} input
 */
export async function executeHosted({ authorization, plan, transport, directory, now }) {
  assertAuthorized(authorization, plan, { now });
  const auth = /** @type {import("./consent.mjs").RemoteAuthorization} */ (authorization);
  const base = { repository: plan.repository, workflow: plan.workflow };
  if (!(await transport.workflowExists({ ...base, revision: plan.revision }))) {
    throw new HostedRunError(`Workflow ${plan.workflow} does not exist at revision ${plan.revision}. Dumbass does not create or push workflows; commit the reviewed workflow first.`);
  }
  let runId = null;
  const cleanup = { remoteArtifactDeleted: false, remoteArtifactDeleteError: null };
  try {
    ({ runId } = await transport.dispatch({ ...base, ref: plan.ref, revision: plan.revision }));
    const { conclusion } = await transport.waitForRun({ repository: plan.repository, runId });
    if (conclusion !== "success") throw new HostedRunError(`Hosted run ${runId} finished with ${conclusion}`, { runId, conclusion });
    const files = await transport.download({ repository: plan.repository, runId, artifactName: plan.artifactName, directory });
    return {
      files,
      provenance: { provider: "github-actions", repository: plan.repository, revision: plan.revision, workflow: plan.workflow, run_id: runId, authorization_id: auth.authorization_id },
      cleanup,
    };
  } finally {
    // Remove the remote copy as soon as it is no longer needed, even when the run failed part-way.
    if (runId !== null) {
      try {
        cleanup.remoteArtifactDeleted = await transport.deleteArtifact({ repository: plan.repository, runId, artifactName: plan.artifactName });
      } catch (error) {
        cleanup.remoteArtifactDeleteError = error instanceof Error ? error.message : String(error);
      }
    }
  }
}

/** @type {(args: string[]) => Promise<{ stdout: string }>} */
function defaultGh(args) {
  return new Promise((resolve, reject) => {
    execFile("gh", args, { timeout: 45 * 60_000, maxBuffer: 8 * 1024 * 1024 }, (error, stdout) => (error ? reject(new Error(`gh ${args.slice(0, 2).join(" ")} failed: ${error.message.split("\n")[0]}`)) : resolve({ stdout: String(stdout) })));
  });
}

/**
 * Transport built on the GitHub CLI. The CLI holds the credentials; this code never reads, logs or
 * forwards a token. Arguments are passed as an array, never through a shell.
 * Status: written against the CLI's documented behavior; it has not been exercised against live
 * GitHub in this repository's checks.
 * @param {(args: string[]) => Promise<{ stdout: string }>} [gh]
 * @returns {HostedTransport}
 */
export function ghCliTransport(gh = defaultGh) {
  return {
    async workflowExists({ repository, workflow, revision }) {
      try {
        await gh(["api", `repos/${repository}/contents/.github/workflows/${workflow}?ref=${revision}`, "--silent"]);
        return true;
      } catch {
        return false;
      }
    },
    async dispatch({ repository, workflow, ref, revision }) {
      const startedAt = Date.now() - 5000;
      await gh(["workflow", "run", workflow, "--repo", repository, "--ref", ref, "-f", `expected_sha=${revision}`]);
      for (let attempt = 0; attempt < 10; attempt += 1) {
        await new Promise((r) => setTimeout(r, 3000));
        const { stdout } = await gh(["run", "list", "--repo", repository, "--workflow", workflow, "--event", "workflow_dispatch", "--limit", "5", "--json", "databaseId,createdAt,headSha"]);
        const runs = JSON.parse(stdout).filter((r) => Date.parse(r.createdAt) >= startedAt && r.headSha === revision);
        if (runs.length) return { runId: String(runs[0].databaseId) };
      }
      throw new HostedRunError("The dispatched run could not be identified at the authorized revision");
    },
    async waitForRun({ repository, runId }) {
      try { await gh(["run", "watch", runId, "--repo", repository, "--exit-status"]); } catch { /* conclusion is read below */ }
      const { stdout } = await gh(["run", "view", runId, "--repo", repository, "--json", "conclusion"]);
      return { conclusion: String(JSON.parse(stdout).conclusion ?? "unknown") };
    },
    async download({ repository, runId, artifactName, directory }) {
      await gh(["run", "download", runId, "--repo", repository, "-n", artifactName, "-D", directory]);
      return [directory];
    },
    async deleteArtifact({ repository, runId, artifactName }) {
      check("id", artifactName, "artifact name");
      const { stdout } = await gh(["api", `repos/${repository}/actions/runs/${runId}/artifacts`, "--jq", `.artifacts[] | select(.name == "${artifactName}") | .id`]);
      const ids = stdout.split("\n").map((s) => s.trim()).filter(Boolean);
      for (const id of ids) await gh(["api", "-X", "DELETE", `repos/${repository}/actions/artifacts/${id}`]);
      return ids.length > 0;
    },
  };
}
